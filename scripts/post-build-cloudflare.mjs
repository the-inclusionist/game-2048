// Post-build that writes `dist/_headers` with the paths at the right `base`. Runs only on the production
// build (after `vite build`); does nothing in dev. The old `app/public/_headers` went obsolete the day the
// game started landing in `dist/game-2048/*` in production: a `_headers` INSIDE `dist/game-2048/` is NOT
// read by CF Pages, which only looks at the root of `pages_build_output_dir` (`dist/`).

import { writeFileSync, existsSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const DIST = join(REPO, 'dist');
// `base` is always of the form `/game-2048` (no trailing slash) or empty for root.
const base = (process.env.INCL_BASE || '/').replace(/\/+$/, '/').replace(/\/+$/, '');
const prefix = base;

if (!existsSync(DIST)) {
  console.error(`post-build: ${DIST} does not exist. Did you run \`vite build\`?`);
  process.exit(1);
}

/*
 * The CF Pages header file. The rules apply to the URL the BROWSER REQUESTS, not to the file name on
 * disk, so they carry the `prefix`. Without `no-cache` on `sw.js` / `index.html` / `manifest`, the PWA's
 * own update mechanism (`vite-plugin-pwa` through Workbox precaches by content-hash and auto-updates, but
 * only if the edge is not serving a stale version). Vite's bundles (`assets/*-[hash].*`) are safely
 * immutable — the hash changes when the content does.
 */
const headers = `# generated by scripts/post-build-cloudflare.mjs

${prefix}/sw.js
  Cache-Control: no-cache
${prefix}/index.html
  Cache-Control: no-cache
${prefix}/manifest.webmanifest
  Cache-Control: no-cache
${prefix}/assets/*
  Cache-Control: public, max-age=31536000, immutable
${prefix}/vendor/*
  Cache-Control: public, max-age=31536000, immutable
`;

writeFileSync(join(DIST, '_headers'), headers);
console.log(`post-build: wrote dist/_headers (prefix: ${prefix || '/'})`);

/*
 * And if Vite already copied the OLD `_headers` into the subfolder, remove it: only the new one at the
 * root survives. The old had unprefixed paths (`/sw.js`), which for CF Pages would have served `sw.js`
 * from the ORIGIN root — which does not even exist in this game's deploy.
 */
if (prefix) {
  const stale = join(DIST, prefix.replace(/^\//, ''), '_headers');
  if (existsSync(stale)) {
    rmSync(stale);
    console.log(`post-build: removed stale ${stale.slice(REPO.length + 1)}`);
  }
}
